// Смещение к МСК (+3ч): граница суток по Москве (аудитория клуба), чтобы мысль
// менялась в местную полночь, а не в 3 ночи по UTC.
const MSK_OFFSET_MS = 3 * 60 * 60 * 1000;

/**
 * Мысль дня на момент nowMs — детерминированно по дню (МСК), по кругу через
 * весь список. ЕДИНЫЙ источник для карточки (home.js) и ежедневного пуша
 * (push-scheduler.js), поэтому пуш и карточка всегда показывают одну и ту же
 * мысль. Возвращает { text, author }: строке подставляем «Анна Бусел»,
 * объекту — его собственного автора.
 */
function thoughtForDate(nowMs) {
  const dayIndex = Math.floor((nowMs + MSK_OFFSET_MS) / 86400000);
  const item = THOUGHTS[dayIndex % THOUGHTS.length];
  return typeof item === 'string'
    ? { text: item, author: 'Анна Бусел' }
    : { text: item.text, author: item.author };
}

module.exports = { THOUGHTS, thoughtForDate };
