/// Категории разборов Анны.
/// Источник: g1orgi89/reader-bot — таксономия из Telegram-бота, использовалась 5 лет.
///
/// Используются как фильтры в каталоге (4.10), поиске, опросе при онбординге.
///
/// АРХИТЕКТУРА — разделение значения в БД и UI label (13.05.2026):
///
/// В БД (`Book.categories`) категории хранятся КАПСОМ — это наследие Telegram-бота
/// Анны, и менять данные нет смысла (re-seed, миграция, новые книги из админки
/// будут приходить капсом). При этом КАПС на UI:
///   - читается на 13-20% медленнее (Nielsen Norman Group)
///   - воспринимается как «крик» — противоречит тёплому бренду психолога
///   - длинные слова (СЕМЕЙНЫЕ ОТНОШЕНИЯ) занимают много места на чипах
///   - противоречит Apple HIG: для navigation/chips рекомендуется sentence case
///   - не соответствует прототипу v4.2 (там Title Case)
///
/// Решение: храним в БД капсом, на UI показываем sentence case через `labelFor()`.
/// Фильтрация в `category_chips.dart` использует исходное значение (`all`),
/// label — только для отображения.
///
/// При добавлении 15-й категории — Анна сначала добавляет книги с этой
/// категорией через админку, потом мы добавляем её сюда и выпускаем релиз.
///
/// Если в будущем потребуется редактирование через админку (без релиза) —
/// заменим этот файл на API `/api/books/categories` + Riverpod provider.
class BookCategories {
  BookCategories._();

  /// Карта: значение в БД (КАПС) → label для UI (sentence case).
  ///
  /// Порядок ключей — порядок частоты использования в каталоге Анны.
  /// LinkedHashMap гарантирует сохранение порядка в Dart.
  static const Map<String, String> _labels = {
    'КРИЗИСЫ': 'Кризисы',
    'Я — ЖЕНЩИНА': 'Я — женщина',
    'ЛЮБОВЬ': 'Любовь',
    'ОТНОШЕНИЯ': 'Отношения',
    'СЕМЕЙНЫЕ ОТНОШЕНИЯ': 'Семейные отношения',
    'ПОИСК СЕБЯ': 'Поиск себя',
    'СМЫСЛ ЖИЗНИ': 'Смысл жизни',
    'СЧАСТЬЕ': 'Счастье',
    'ОДИНОЧЕСТВО': 'Одиночество',
    'СМЕРТЬ': 'Смерть',
    'ДЕНЬГИ': 'Деньги',
    'ВРЕМЯ И ПРИВЫЧКИ': 'Время и привычки',
    'ОБЩЕСТВО': 'Общество',
    'ДОБРО И ЗЛО': 'Добро и зло',
  };

  /// 14 категорий Анны — значения как в БД (для фильтрации).
  static List<String> get all => _labels.keys.toList(growable: false);

  /// Получить отображаемый label по значению из БД.
  /// Если категория не найдена в карте — возвращаем значение как есть
  /// (fallback для новых категорий до их добавления в карту).
  static String labelFor(String value) => _labels[value] ?? value;
}
