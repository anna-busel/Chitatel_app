import 'package:flutter/foundation.dart';

/// Можно ли продавать в приложении на текущей платформе.
///
/// 16.10.2026: Android выходит БЕСПЛАТНЫМ. Профиль продавца Google Play на
/// грузинское ИП открыть нельзя (AI-CONTEXT-7, раздел 2.5), товаров в Play нет.
/// Правило Google Payments: в приложении нельзя показывать цены, кнопки
/// покупки и вести к оплате вне Google Play. Можно — открывать то, к чему у
/// человека уже есть доступ (купленное на iPhone, ручная выдача в админке).
///
/// Поэтому на Android: без цен, без «Купить», без тарифов клуба. Платное
/// показывается как «Для участниц», купленное — как «Доступно». iOS не
/// меняется ни в чём.
///
/// Когда оплата в Google Play появится — вернуть true для Android и пройтись
/// по местам, где читается этот флаг (grep kPurchasesEnabled).
bool get kPurchasesEnabled => defaultTargetPlatform != TargetPlatform.android;

/// Подпись на карточке, когда доступ к платному уже есть.
String get kOwnedLabel => kPurchasesEnabled ? 'Куплено' : 'Доступно';

/// Подпись на карточке платного разбора без доступа (только Android).
const String kMembersOnlyLabel = 'Для участниц';
